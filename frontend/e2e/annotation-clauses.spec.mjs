import { test, expect } from '@playwright/test'

test.skip(!process.env.DROPDOWN_BACKEND, 'Requires isolated local annotation backend')

test('review ECOG and another clause, undo, save a draft, and inspect provenance on mobile', async ({ page }, info) => {
  const backend = new URL(process.env.DROPDOWN_BACKEND)
  expect(['127.0.0.1', 'localhost']).toContain(backend.hostname)
  let saved
  await page.route('**/api/**', async route => {
    const request = route.request(), url = new URL(request.url()), path = url.pathname.replace(/^\/api/, '')
    expect(request.method() === 'GET' && /^\/(health|(research|tnbc)\/cases|research\/trials|annotations\/NCT\d{8})$/.test(path) || request.method() === 'POST' && (/^\/(research|tnbc)\/cases\/[^/]+\/evaluate$/.test(path) || /^\/annotations\/NCT\d{8}\/versions$/.test(path))).toBe(true)
    const response = await route.fetch({ url: `${backend.origin}${path}${url.search}` })
    if (path.endsWith('/versions') && request.method() === 'POST' && response.ok()) saved = await response.json()
    await route.fulfill({ response })
  })
  await page.goto('/')
  await page.getByRole('button', { name: 'Research Tools', exact: true }).click()
  await page.getByRole('button', { name: 'Protocol annotation', exact: true }).click()
  await expect(page.locator('.clause-card').first()).toBeVisible()
  await expect(page.getByLabel('Span start')).not.toBeVisible()
  await expect(page.getByLabel('Criterion JSON')).not.toBeVisible()
  await page.locator('.clause-card').filter({ hasText: 'ECOG' }).click()
  const quotation = page.getByLabel('Selected clause quotation')
  const ecog = await quotation.textContent()
  expect(ecog.length).toBeLessThan(300)
  expect(ecog).toContain('ECOG')
  await expect(page.getByLabel('Value', { exact: true })).toHaveValue('')
  await page.getByLabel('Criterion polarity').selectOption('inclusion')
  await page.getByRole('button', { name: 'Confirm draft', exact: true }).click()
  await page.locator('.clause-card').filter({ hasText: 'Metastatic disease' }).click()
  await page.getByLabel('Uncertainty note (optional)').fill('Software test: requires scope review.')
  await page.getByRole('button', { name: 'Mark ambiguous', exact: true }).click()
  await expect(page.getByText(/2 of .* candidate clauses have drafts/)).toBeVisible()
  await page.getByRole('button', { name: 'Delete draft', exact: true }).click()
  await expect(page.getByText(/1 of .* candidate clauses have drafts/)).toBeVisible()
  await page.getByRole('button', { name: 'Undo last draft change', exact: true }).click()
  await expect(page.getByText(/2 of .* candidate clauses have drafts/)).toBeVisible()
  await page.getByText('Advanced Mode: annotation details', { exact: true }).click()
  await page.getByLabel('Reviewer identifier or pseudonym').fill('software-ux-test-only')
  await page.getByLabel('Audit note for save').fill('Software regression only; not clinical gold.')
  await page.getByRole('button', { name: 'Save draft', exact: true }).click()
  await expect(page.getByText(/Draft saved\./)).toBeVisible()
  expect(saved.bundle.audit.stage).toBe('draft')
  expect(saved.bundle.reference.criteria).toHaveLength(2)
  expect(saved.bundle.reference.inventory_review.status).toBe('unreviewed')
  expect(saved.bundle.reference.criteria.every(node => node.boundary_review.status === 'unreviewed')).toBe(true)
  expect(saved.bundle.reference.criteria.find(node => node.original.text.includes('ECOG')).original.text).toBe(ecog)
  await page.locator('.clause-card').filter({ hasText: 'ECOG' }).click()
  await page.getByRole('link', { name: /Linked to exact saved source/ }).click()
  await expect(page.getByRole('link', { name: 'Open ClinicalTrials.gov study' })).toBeVisible()
  await page.setViewportSize({ width: 390, height: 844 })
  await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.screenshot({ path: info.outputPath('clause-review-mobile.png'), fullPage: true })
  await info.attach('software-test-draft', { body: JSON.stringify(saved.bundle), contentType: 'application/json' })
})
