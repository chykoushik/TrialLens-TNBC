import { test, expect } from '@playwright/test'

test.skip(!process.env.DROPDOWN_BACKEND, 'Requires the local offline annotation backend')

async function choose(page, name, index) {
  const control = page.getByRole('combobox', { name, exact: true })
  await expect(control).toBeEnabled()
  await control.click()
  await expect.poll(() => control.evaluate(node => node.matches(':open'))).toBe(true)
  await page.keyboard.press('Home')
  for (let i = 0; i < index; i++) await page.keyboard.press('ArrowDown')
  await page.keyboard.press('Enter')
}

test('public protocol annotation uses real source, physical selection, versioned draft import and strict gating', async ({ page }, info) => {
  const backend = new URL(process.env.DROPDOWN_BACKEND)
  expect(['127.0.0.1', 'localhost']).toContain(backend.hostname)
  let saved
  await page.route('**/api/**', async route => {
    const request = route.request(), url = new URL(request.url()), path = url.pathname.replace(/^\/api/, '')
    const read = request.method() === 'GET' && (/^\/(health|(research|tnbc)\/cases|research\/trials)$/.test(path) || /^\/annotations\/NCT\d{8}(\/versions\/[a-f0-9]{32})?$/.test(path))
    const post = request.method() === 'POST' && (/^\/(research|tnbc)\/cases\/[^/]+\/evaluate$/.test(path) || /^\/annotations\/NCT\d{8}\/(validate|import|versions|versions\/[a-f0-9]{32}\/evaluate)$/.test(path))
    expect(read || post, `Offline route: ${path}`).toBe(true)
    const response = await route.fetch({ url: `${backend.origin}${path}${url.search}` })
    if (path.endsWith('/versions') && request.method() === 'POST' && response.ok()) saved = await response.json()
    await route.fulfill({ response })
  })
  await page.goto('/')
  await page.getByRole('button', { name: 'Research Tools', exact: true }).click()
  await page.getByRole('button', { name: 'Protocol annotation', exact: true }).click()
  await expect(page.getByLabel('Annotation snapshot')).toBeEnabled()
  await expect(page.getByLabel('Annotation study').locator('option')).toHaveCount(5)
  await expect(page.getByLabel('Annotation snapshot').locator('option')).toHaveCount(2)
  await expect(page.getByLabel('Synthetic portfolio')).toHaveCount(0)
  for (const index of [1, 2, 0]) {
    await choose(page, 'Annotation study', index)
    await expect(page.getByLabel('Annotation snapshot')).toBeEnabled()
  }
  for (const index of [1, 0, 1]) {
    await choose(page, 'Annotation snapshot', index)
    await expect(page.getByRole('button', { name: 'Save draft', exact: true })).toBeEnabled()
  }
  await page.getByText('Advanced Mode: annotation details', { exact: true }).click()
  const pre = page.getByLabel('Exact original eligibility text')
  const source = await pre.textContent()
  await pre.scrollIntoViewIfNeeded()
  const box = await pre.evaluate(node => {
    const walker = document.createTreeWalker(node, NodeFilter.SHOW_TEXT), text = walker.nextNode()
    const range = document.createRange(); range.setStart(text, 0); range.setEnd(text, Math.min(9, text.textContent.length))
    const box = range.getBoundingClientRect()
    return { x: box.x, y: box.y, width: box.width, height: box.height }
  })
  await page.mouse.move(box.x + 1, box.y + box.height / 2)
  await page.mouse.down()
  await page.mouse.move(box.x + box.width - 1, box.y + box.height / 2, { steps: 12 })
  await page.mouse.up()
  await expect(page.getByRole('button', { name: 'Create criterion from span', exact: true })).toBeEnabled()
  const start = Number(await page.getByLabel('Span start', { exact: true }).inputValue())
  const end = Number(await page.getByLabel('Span end', { exact: true }).inputValue())
  expect(end).toBeGreaterThan(start)
  await page.getByRole('button', { name: 'Create criterion from span', exact: true }).click()
  if (!await page.getByLabel('Span start').isVisible()) await page.getByText('Advanced Mode: annotation details', { exact: true }).click()
  await expect(page.getByText('Boundary: unreviewed', { exact: true })).toBeVisible()
  await choose(page, 'Annotation study', 1)
  await expect(page.getByLabel('Annotation snapshot')).toBeEnabled()
  await choose(page, 'Annotation study', 0)
  await expect(page.getByLabel('Annotation snapshot')).toBeEnabled()
  await choose(page, 'Annotation snapshot', 1)
  if (!await page.getByLabel('Span start').isVisible()) await page.getByText('Advanced Mode: annotation details', { exact: true }).click()
  await expect(page.getByText('Boundary: unreviewed', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Home', exact: true }).click()
  await page.getByRole('button', { name: 'Research Tools', exact: true }).click()
  if (!await page.getByLabel('Span start').isVisible()) await page.getByText('Advanced Mode: annotation details', { exact: true }).click()
  await expect(page.getByText('Boundary: unreviewed', { exact: true })).toBeVisible()
  await page.getByLabel('Reviewer identifier or pseudonym').fill('browser-software-test-only')
  await page.getByLabel('Review and audit note').fill('Software test draft only; not clinical gold or human review.')
  await page.getByRole('button', { name: 'Validate annotation', exact: true }).click()
  await expect(page.getByText(/Schema and source checks passed/)).toBeVisible()
  await page.getByRole('button', { name: 'Save new version & export JSON', exact: true }).click()
  await expect(page.getByText(/Saved new draft version inside/)).toBeVisible()
  expect(saved.bundle.reference.criteria[0].original.text).toBe(Array.from(source).slice(start, end).join(''))
  expect(saved.bundle.reference.inventory_review.status).toBe('unreviewed')
  await page.getByText('Deterministic JSON export / import', { exact: true }).click()
  await expect(page.getByLabel('Review bundle JSON')).toHaveValue(saved.export_json)
  const modified = structuredClone(saved.bundle); modified.source.sha256 = '0'.repeat(64)
  await page.getByLabel('Review bundle JSON').fill(JSON.stringify(modified))
  await page.getByRole('button', { name: 'Import as local draft', exact: true }).click()
  await expect(page.getByRole('alert')).toContainText('provenance mismatch')
  await page.getByLabel('Review bundle JSON').fill(saved.export_json)
  await page.getByRole('button', { name: 'Import as local draft', exact: true }).click()
  await expect(page.getByText(/Imported claims are unverified/)).toBeVisible()
  await expect(page.getByLabel('Save stage')).toHaveValue('draft')
  await page.getByRole('button', { name: 'Save new version & export JSON', exact: true }).click()
  await expect(page.getByText(/Saved new draft version inside/)).toBeVisible()
  await page.getByText('Evaluate saved approved labels offline', { exact: true }).click()
  await page.getByRole('button', { name: 'Evaluate saved version', exact: true }).click()
  await expect(page.getByRole('alert')).toContainText('Drafts cannot supply evaluation reference labels')
  await info.attach('draft-export-not-gold', { body: saved.export_json, contentType: 'application/json' })
  await page.setViewportSize({ width: 390, height: 844 })
  await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.screenshot({ path: info.outputPath('annotation-mobile.png'), fullPage: true })
})
