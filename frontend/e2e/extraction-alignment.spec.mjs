import { test, expect } from '@playwright/test'

test.skip(!process.env.DROPDOWN_BACKEND, 'Requires isolated offline backend')

test('real saved extraction review compares source, corrects drafts and preserves review gating', async ({ page }, info) => {
  const backend = new URL(process.env.DROPDOWN_BACKEND)
  expect(backend.hostname).toBe('127.0.0.1')
  let saved
  await page.route('**/*', async route => {
    const request = route.request(), url = new URL(request.url())
    if (!['127.0.0.1', 'localhost'].includes(url.hostname)) return route.abort()
    if (!url.pathname.startsWith('/api/')) return route.continue()
    const path = url.pathname.replace(/^\/api/, '')
    const allowed = request.method() === 'GET' && /^\/(health|(research|tnbc)\/cases|research\/trials|annotations\/NCT\d{8})$/.test(path)
      || request.method() === 'POST' && (/^\/(research|tnbc)\/cases\/[^/]+\/evaluate$/.test(path) || /^\/annotations\/NCT\d{8}\/versions$/.test(path))
    expect(allowed).toBe(true)
    const response = await route.fetch({ url: `${backend.origin}${path}${url.search}` })
    if (path.endsWith('/versions') && response.ok()) saved = await response.json()
    await route.fulfill({ response })
  })
  await page.goto('/')
  await page.getByRole('button', { name: 'Research Tools', exact: true }).click()
  await page.getByRole('button', { name: 'Protocol annotation', exact: true }).click()
  await expect(page.locator('.clause-card')).toHaveCount(24)
  await page.locator('.clause-card').filter({ hasText: 'Clinically significant GI disorders' }).click()
  const proposal = page.getByRole('region', { name: 'Saved model proposal' })
  await expect(proposal).toContainText('Source alignment checked')
  await expect(page.getByLabel('Selected clause quotation')).toHaveText('* Clinically significant GI disorders')
  await expect(page.getByLabel('Span start')).not.toBeVisible()
  await expect(proposal.locator('pre')).not.toBeVisible()
  await page.getByRole('button', { name: 'Correct', exact: true }).click()
  await page.getByLabel('Criterion polarity').selectOption('exclusion')
  await page.getByRole('button', { name: 'Confirm draft', exact: true }).click()
  await expect.poll(() => saved?.bundle.reference.criteria.length).toBe(1)
  expect(saved.bundle.audit.stage).toBe('draft')
  expect(saved.bundle.reference.inventory_review.status).toBe('unreviewed')
  expect(saved.bundle.reference.criteria[0].boundary_review.status).toBe('unreviewed')
  expect(saved.bundle.reference.criteria[0].polarity.review.status).toBe('unreviewed')
  await page.locator('.clause-card').filter({ hasText: 'Prior irinotecan' }).click()
  await expect(page.getByText('Compound meaning is unresolved. Do not assume how the conditions combine.')).toBeVisible()
  await page.getByRole('button', { name: 'Skip', exact: true }).click()
  await expect(page.getByText(/1 skipped this session/)).toBeVisible()
  expect(saved.bundle.reference.criteria).toHaveLength(1)
  await page.setViewportSize({ width: 390, height: 844 })
  await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.screenshot({ path: info.outputPath('alignment-review-mobile.png'), fullPage: true })
})
