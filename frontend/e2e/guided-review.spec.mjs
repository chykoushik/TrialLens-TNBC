import { navigate } from './navigation.mjs'
import { test, expect } from '@playwright/test'

test('guided review uses real backend and preserves review history on desktop and mobile', async ({ page }, info) => {
  const errors = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto('/')
  await expect(page.getByRole('navigation', { name: 'Main navigation' }).getByRole('button')).toHaveText(['Home', 'Evidence Review', 'Research Results'])
  await page.screenshot({ path: info.outputPath('home-desktop.png'), fullPage: true })
  await page.getByRole('button', { name: 'Start Evidence Review', exact: true }).click()
  await page.getByRole('button', { name: 'Try a Demo', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Continue', exact: true })).toBeEnabled()
  await expect(page.getByRole('heading', { name: 'Choose a trial scenario' })).toBeVisible()
  await page.getByLabel('Trial and evidence scenario').selectOption('tnbc-conflicting-records')
  await expect(page.getByRole('button', { name: 'Continue', exact: true })).toBeEnabled()
  await page.getByLabel('Trial and evidence scenario').selectOption('tnbc-record-gaps')
  await expect(page.getByRole('button', { name: 'Continue', exact: true })).toBeEnabled()
  await page.getByRole('button', { name: 'Continue', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Explore available evidence' })).toBeVisible()
  await page.locator('.demo-observations button').first().click()
  await expect(page.getByRole('heading', { name: 'Selected source record' })).toBeVisible()
  await page.getByRole('button', { name: 'Continue', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Understand the assessments' })).toBeVisible()
  await page.getByRole('button', { name: 'Continue', exact: true }).click()
  await expect(page.getByRole('radio').first()).toBeEnabled()
  await page.getByRole('radio').first().check()
  await page.getByRole('button', { name: 'Apply fictional report', exact: true }).click()
  await expect(page.getByLabel('What changed')).toBeVisible()
  await page.getByRole('button', { name: 'Continue', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Applied fictional report history' })).toBeVisible()
  await expect(page.locator('.journey-stage > ol > li')).toHaveCount(1)
  await page.getByRole('button', { name: 'Back', exact: true }).click()
  await page.setViewportSize({ width: 390, height: 844 })
  await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.screenshot({ path: info.outputPath('guided-mobile.png'), fullPage: true })
  await page.reload()
  await expect(page.getByText(/Fictional demonstration restored and checked/)).toHaveCount(0)
  await page.getByRole('button', { name: 'Start Evidence Review', exact: true }).click()
  await page.getByRole('button', { name: 'Try a Demo', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Review a suggested report' })).toBeVisible()
  await page.getByRole('button', { name: 'Continue', exact: true }).click()
  await expect(page.locator('.journey-stage > ol > li')).toHaveCount(1)
  await page.getByRole('button', { name: 'Restart evidence review', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Choose a trial scenario' })).toBeVisible()
  await expect(page.getByRole('button', { name: 'Continue', exact: true })).toBeEnabled()
  await expect.poll(() => page.evaluate(() => Object.keys(JSON.parse(localStorage.getItem('triallens.fictional-demo.v1')).outcomes).length)).toBe(0)
  expect(errors).toEqual([])
})

test('saved registry provenance and aggregate research are connected', async ({ page }, info) => {
  await page.goto('/')
  await navigate(page, 'Explore Trials')
  await page.locator('.simple-trial-list button').filter({ hasText: 'NCT01770353' }).click()
  await expect(page.getByRole('link', { name: /Read the ClinicalTrials.gov record/ })).toHaveAttribute('href', 'https://clinicaltrials.gov/study/NCT01770353')
  await page.getByText('Saved source provenance', { exact: true }).click()
  await expect(page.getByText(/SHA-256:/)).toBeVisible()
  await navigate(page, 'Research Results')
  await expect(page.getByRole('heading', { name: 'Reusing calculations saves work' })).toBeVisible()
  await page.screenshot({ path: info.outputPath('research-overview-desktop.png'), fullPage: true })
  await page.getByText('Methods, measurements and artifact sources', { exact: true }).click()
  await expect(page.getByRole('heading', { name: 'METABRIC archival mapping' })).toBeVisible()
  await expect(page.getByRole('heading', { name: 'TCGA extraction evaluation' })).toBeVisible()
  await expect(page.getByText('Offline: live inference is not ready.')).toBeVisible()
  await expect(page.getByRole('region', { name: 'METABRIC archival mapping saved aggregate table' })).toBeVisible()
  await page.screenshot({ path: info.outputPath('research-desktop.png'), fullPage: true })
  await page.setViewportSize({ width: 390, height: 844 })
  await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.screenshot({ path: info.outputPath('research-mobile.png'), fullPage: true })
})

for (const width of [390, 768]) {
  test(`a new visitor completes every stage at ${width}px`, async ({ page }, info) => {
    await page.setViewportSize({ width, height: 900 })
    await page.goto('/')
    await page.screenshot({ path: info.outputPath(`home-${width}.png`), fullPage: true })
    await page.getByRole('button', { name: 'Start Evidence Review', exact: true }).click()
  await page.getByRole('button', { name: 'Try a Demo', exact: true }).click()
    for (let step = 0; step < 4; step++) {
      await expect(page.getByRole('button', { name: 'Continue', exact: true })).toBeEnabled()
      await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
      if (step === 3) {
        await page.getByRole('radio').first().check()
        await page.getByRole('button', { name: 'Apply fictional report', exact: true }).click()
        await expect(page.getByLabel('What changed')).toBeVisible()
      }
      await page.getByRole('button', { name: 'Continue', exact: true }).click()
    }
    await expect(page.getByRole('heading', { name: 'See your updated result' })).toBeVisible()
    await expect(page.locator('.journey-stage > ol > li')).toHaveCount(1)
    await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
    await navigate(page, 'Research Results')
    await expect(page.getByRole('heading', { name: 'Reusing calculations saves work' })).toBeVisible()
    await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  })
}
